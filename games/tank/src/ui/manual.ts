/** 게임 설명 팝업 */
export function showManualModal() {
  const wrap = document.createElement('div');
  wrap.className = 'rank-modal';
  wrap.innerHTML = `<div class="rank-box manual-box">
    <div class="rank-head"><h3>📖 게임 설명</h3><button class="btn small-btn" data-close>닫기</button></div>
    <div class="rank-scroll manual">${MANUAL.map(([t, b]) => `<details><summary>${t}</summary><div class="mbody">${b}</div></details>`).join('')}</div>
  </div>`;
  wrap.addEventListener('click', (e) => {
    if (e.target === wrap || (e.target as HTMLElement).closest('[data-close]')) wrap.remove();
  });
  document.body.append(wrap);
}
